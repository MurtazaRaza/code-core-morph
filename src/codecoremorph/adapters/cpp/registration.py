"""Characterization tests in a CMake build (``register_test_files``, SPEC §7.11 step 3).

The tests' directory gets a generated ``CMakeLists.txt`` with one GoogleTest executable,
``codecoremorph_characterization``, registered with CTest. It links the library targets that
compile the characterized symbols' source files, found at configure time from the targets'
``SOURCES``, so the core needs to know nothing about the project's targets. GoogleTest is the
project's own when it builds one (a vendored ``gtest_main``), else ``find_package(GTest)``.

The top-level ``CMakeLists.txt`` gets a marked block that adds the directory; removing the
tests removes the block.
"""

from __future__ import annotations

from codecoremorph.patching.textfile import majority_newline

TARGET = "codecoremorph_characterization"
BEGIN = "# >>> CodeCoreMorph characterization tests (SPEC §7.11)"
END = "# <<< CodeCoreMorph characterization tests"

_LINK_SCAN = """\
# The library targets that compile the characterized code.
set(_ccm_links "")
set(_ccm_dirs "${CMAKE_SOURCE_DIR}")
while(_ccm_dirs)
  list(GET _ccm_dirs 0 _ccm_dir)
  list(REMOVE_AT _ccm_dirs 0)
  get_property(_ccm_subdirs DIRECTORY "${_ccm_dir}" PROPERTY SUBDIRECTORIES)
  list(APPEND _ccm_dirs ${_ccm_subdirs})
  get_property(_ccm_targets DIRECTORY "${_ccm_dir}" PROPERTY BUILDSYSTEM_TARGETS)
  foreach(_ccm_target IN LISTS _ccm_targets)
    get_target_property(_ccm_type "${_ccm_target}" TYPE)
    if(_ccm_type MATCHES "^(STATIC|SHARED|OBJECT|INTERFACE)_LIBRARY$")
      get_target_property(_ccm_target_sources "${_ccm_target}" SOURCES)
      get_target_property(_ccm_source_dir "${_ccm_target}" SOURCE_DIR)
      if(_ccm_target_sources)
        foreach(_ccm_source IN LISTS _ccm_target_sources)
          get_filename_component(_ccm_path "${_ccm_source}" ABSOLUTE BASE_DIR "${_ccm_source_dir}")
          if(_ccm_path IN_LIST _ccm_sources)
            list(APPEND _ccm_links "${_ccm_target}")
            break()
          endif()
        endforeach()
      endif()
    endif()
  endforeach()
endwhile()
if(_ccm_links)
  list(REMOVE_DUPLICATES _ccm_links)
endif()

# GoogleTest: the project's own build of it, or an installed one.
if(TARGET gtest_main)
  set(_ccm_gtest gtest_main)
elseif(TARGET GTest::gtest_main)
  set(_ccm_gtest GTest::gtest_main)
else()
  find_package(GTest REQUIRED)
  if(TARGET GTest::gtest_main)
    set(_ccm_gtest GTest::gtest_main)
  else()
    set(_ccm_gtest GTest::Main)
  endif()
endif()
"""


def _quote(path: str) -> str:
    return '"' + path.replace("\\", "/").replace('"', '\\"') + '"'


def characterization_cmake(test_files: list[str], sources: list[str]) -> str:
    """The tests directory's ``CMakeLists.txt``. ``test_files`` are relative to the directory;
    ``sources`` (the files defining the characterized symbols) to the project root."""
    lines = [
        "# Generated by CodeCoreMorph: characterization tests, which pin down the code's",
        "# behavior before the migration (SPEC §7.11). CodeCoreMorph rewrites this file.",
        "cmake_policy(SET CMP0057 NEW)  # if(... IN_LIST ...)",
        "",
        "set(_ccm_sources",
        *(f"  {_quote('${CMAKE_SOURCE_DIR}/' + s)}" for s in sorted(set(sources))),
        ")",
        _LINK_SCAN,
        f"add_executable({TARGET}",
        *(f"  {_quote(f)}" for f in test_files),
        ")",
        f"target_link_libraries({TARGET} PRIVATE ${{_ccm_links}} ${{_ccm_gtest}})",
        f"add_test(NAME {TARGET} COMMAND {TARGET})",
        "",
    ]
    return "\n".join(lines)


def without_block(text: str) -> str:
    """``text`` (a top-level ``CMakeLists.txt``) without the characterization block and the
    blank line ``with_block`` put before it."""
    start = text.find(BEGIN)
    if start < 0:
        return text
    end = text.find(END, start)
    end = len(text) if end < 0 else end + len(END)
    for newline in ("\r\n", "\n"):
        if text.startswith(newline, end):
            end += len(newline)
            break
    head = text[:start]
    for newline in ("\r\n", "\n"):
        if head.endswith(newline + newline):
            head = head[: -len(newline)]
            break
    return head + text[end:]


def with_block(text: str, test_dir: str) -> str:
    """``text`` (a top-level ``CMakeLists.txt``) adding ``test_dir`` at its end, once, in the
    file's line endings."""
    newline = majority_newline(text) if "\n" in text else "\n"
    base = without_block(text)
    if base and not base.endswith("\n"):
        base += newline
    block = [BEGIN, "enable_testing()", f"add_subdirectory({_quote(test_dir)})", END]
    return base + newline + newline.join(block) + newline
