"""Characterization tests in a CMake build (``register_test_files``, SPEC §7.11 step 3).

The tests' directory gets a generated ``CMakeLists.txt`` with one GoogleTest executable,
``codecoremorph_characterization``, registered with CTest. It links the library targets that
compile the characterized symbols' source files, found at configure time from the targets'
``SOURCES``, so the core needs to know nothing about the project's targets. GoogleTest is the
project's own when it builds one (a vendored ``gtest_main``), else ``find_package(GTest)``.

The top-level ``CMakeLists.txt`` gets a marked block that adds the directory; removing the
tests removes the block.

A Make build (a Makefile, automake's ``Makefile.am``, or the ``Makefile.in`` configure writes
the Makefile from) gets a marked block of its own at the end of its top-level file instead
(D-89): a program per test, compiled with the project's ``CXXFLAGS`` and linked with the
archives of the libraries that compile the characterized code and the toolchain's GoogleTest,
run before the test target's recipe, each writing its results as GoogleTest XML.
"""

from __future__ import annotations

import posixpath
import re
from collections.abc import Sequence

from codecoremorph.patching.textfile import majority_newline

TARGET = "codecoremorph_characterization"
BEGIN = "# >>> CodeCoreMorph characterization tests (SPEC §7.11)"
END = "# <<< CodeCoreMorph characterization tests"

_LINK_SCAN = r"""
# The library targets that compile the characterized code: those that list one of its files
# in their sources, and those whose include directories hold one (a header, which targets
# rarely list, or a header-only library).
set(_ccm_links "")
set(_ccm_dirs "${CMAKE_SOURCE_DIR}")
while(_ccm_dirs)
  list(GET _ccm_dirs 0 _ccm_dir)
  list(REMOVE_AT _ccm_dirs 0)
  get_property(_ccm_subdirs DIRECTORY "${_ccm_dir}" PROPERTY SUBDIRECTORIES)
  list(APPEND _ccm_dirs ${_ccm_subdirs})
  get_property(_ccm_targets DIRECTORY "${_ccm_dir}" PROPERTY BUILDSYSTEM_TARGETS)
  foreach(_ccm_target IN LISTS _ccm_targets)
    get_target_property(_ccm_type "${_ccm_target}" TYPE)
    if(_ccm_type MATCHES "^(STATIC|SHARED|OBJECT|INTERFACE)_LIBRARY$")
      get_target_property(_ccm_source_dir "${_ccm_target}" SOURCE_DIR)
      set(_ccm_found FALSE)
      get_target_property(_ccm_target_sources "${_ccm_target}" SOURCES)
      if(_ccm_target_sources)
        foreach(_ccm_source IN LISTS _ccm_target_sources)
          get_filename_component(_ccm_path "${_ccm_source}" ABSOLUTE BASE_DIR "${_ccm_source_dir}")
          if(_ccm_path IN_LIST _ccm_sources)
            set(_ccm_found TRUE)
            break()
          endif()
        endforeach()
      endif()
      if(NOT _ccm_found)
        set(_ccm_includes "")
        foreach(_ccm_property INCLUDE_DIRECTORIES INTERFACE_INCLUDE_DIRECTORIES)
          get_target_property(_ccm_value "${_ccm_target}" ${_ccm_property})
          if(_ccm_value)
            list(APPEND _ccm_includes ${_ccm_value})
          endif()
        endforeach()
        foreach(_ccm_include IN LISTS _ccm_includes)
          string(REGEX REPLACE "^\\$<BUILD_INTERFACE:(.*)>$" "\\1" _ccm_include "${_ccm_include}")
          if(_ccm_include STREQUAL "" OR _ccm_include MATCHES "^\\$<")
            continue()  # another generator expression: not a build-tree directory
          endif()
          get_filename_component(_ccm_include "${_ccm_include}" ABSOLUTE
                                 BASE_DIR "${_ccm_source_dir}")
          foreach(_ccm_source IN LISTS _ccm_sources)
            string(FIND "${_ccm_source}" "${_ccm_include}/" _ccm_at)
            if(_ccm_at EQUAL 0)
              set(_ccm_found TRUE)
              break()
            endif()
          endforeach()
          if(_ccm_found)
            break()
          endif()
        endforeach()
      endif()
      if(_ccm_found)
        list(APPEND _ccm_links "${_ccm_target}")
      endif()
    endif()
  endforeach()
endwhile()
if(_ccm_links)
  list(REMOVE_DUPLICATES _ccm_links)
endif()

# GoogleTest: the project's own build of it, or an installed one.
if(TARGET gtest_main)
  set(_ccm_gtest gtest_main)
elseif(TARGET GTest::gtest_main)
  set(_ccm_gtest GTest::gtest_main)
else()
  find_package(GTest REQUIRED)
  if(TARGET GTest::gtest_main)
    set(_ccm_gtest GTest::gtest_main)
  else()
    set(_ccm_gtest GTest::Main)
  endif()
endif()
"""


def _quote(path: str) -> str:
    return '"' + path.replace("\\", "/").replace('"', '\\"') + '"'


def characterization_cmake(test_files: list[str], sources: list[str]) -> str:
    """The tests directory's ``CMakeLists.txt``. ``test_files`` are relative to the directory;
    ``sources`` (the files defining the characterized symbols) to the project root."""
    lines = [
        "# Generated by CodeCoreMorph: characterization tests, which pin down the code's",
        "# behavior before the migration (SPEC §7.11). CodeCoreMorph rewrites this file.",
        "cmake_policy(SET CMP0057 NEW)  # if(... IN_LIST ...)",
        "",
        "set(_ccm_sources",
        *(f"  {_quote('${CMAKE_SOURCE_DIR}/' + s)}" for s in sorted(set(sources))),
        ")",
        _LINK_SCAN,
        f"add_executable({TARGET}",
        *(f"  {_quote(f)}" for f in test_files),
        ")",
        f"target_link_libraries({TARGET} PRIVATE ${{_ccm_links}} ${{_ccm_gtest}})",
        f"add_test(NAME {TARGET} COMMAND {TARGET})",
        "",
    ]
    return "\n".join(lines)


def without_block(text: str) -> str:
    """``text`` (a top-level ``CMakeLists.txt``) without the characterization block and the
    blank line ``with_block`` put before it."""
    start = text.find(BEGIN)
    if start < 0:
        return text
    end = text.find(END, start)
    end = len(text) if end < 0 else end + len(END)
    for newline in ("\r\n", "\n"):
        if text.startswith(newline, end):
            end += len(newline)
            break
    head = text[:start]
    for newline in ("\r\n", "\n"):
        if head.endswith(newline + newline):
            head = head[: -len(newline)]
            break
    return head + text[end:]


def with_block(text: str, test_dir: str) -> str:
    """``text`` (a top-level ``CMakeLists.txt``) adding ``test_dir`` at its end, once, in the
    file's line endings."""
    newline = majority_newline(text) if "\n" in text else "\n"
    base = without_block(text)
    if base and not base.endswith("\n"):
        base += newline
    block = [BEGIN, "enable_testing()", f"add_subdirectory({_quote(test_dir)})", END]
    return base + newline + newline.join(block) + newline


# ------------------------------------------------------------------ a Make build (D-89)

MAKE_TARGET = "codecoremorph-characterization"
# Where each program writes its GoogleTest XML, from the directory make runs in.
GTEST_OUTPUT_DIR = "codecoremorph-gtest"
_LISTED = re.compile(r"^CODECOREMORPH_CHARACTERIZATION = (.*)$", re.MULTILINE)


def make_program(path: str) -> str:
    """The program a characterization test file builds: the file without its extension."""
    return posixpath.splitext(path)[0]


def make_test_targets(makefile: str, configured: Sequence[str]) -> list[str]:
    """The targets that run the tests: the manifest's, else ``check`` or ``test``, whichever
    the Makefile has outside the block."""
    if configured:
        return list(configured)
    text = without_block(makefile)
    for target in ("check", "test"):
        if re.search(rf"^{target}\s*:", text, re.MULTILINE):
            return [target]
    return []


def make_block(
    tests: Sequence[str],
    archives: Sequence[str],
    include_dirs: Sequence[str],
    test_targets: Sequence[str],
    *,
    cxx98: bool,
) -> str:
    """The marked block for ``tests`` (paths from the Makefile's directory), each built from
    its file and linked with ``archives`` and GoogleTest, run before each of
    ``test_targets``. GoogleTest is the toolchain's (the first of ``CMAKE_PREFIX_PATH``), or
    for a C++98/03 build the release that supports it (``CODECOREMORPH_CXX98_PREFIX_PATH``,
    D-38)."""
    names = [make_program(t) for t in tests]
    prefix = (
        "$(CODECOREMORPH_CXX98_PREFIX_PATH)"
        if cxx98
        else "$(firstword $(subst :, ,$(CMAKE_PREFIX_PATH)))"
    )
    includes = " ".join(f"-I{d}" for d in include_dirs)
    linked = " ".join(archives)
    lines = [
        BEGIN,
        f"CODECOREMORPH_GTEST = {prefix}",
        f"CODECOREMORPH_CHARACTERIZATION = {' '.join(names)}",
    ]
    for test, name in zip(tests, names, strict=True):
        # Without -c, which some Makefiles put in their flags: this rule compiles and links.
        lines += [
            f"{name}: {test} {linked}".rstrip(),
            f"\t$(CXX) $(CPPFLAGS) $(filter-out -c,$(CXXFLAGS)) -I$(CODECOREMORPH_GTEST)/include "
            f"{includes} -o $@ {test} {linked} $(LDFLAGS) -L$(CODECOREMORPH_GTEST)/lib "
            "-L$(CODECOREMORPH_GTEST)/lib64 -lgtest_main -lgtest -pthread "
            "$(CODECOREMORPH_RUST_LIBS) $(LDLIBS) $(LIBS)",
        ]
    # Order-only: made before the target's recipe, but not one of its $^ (a recipe that
    # compiles $^ would name the phony target as a file).
    lines += [f"{target}: | {MAKE_TARGET}" for target in test_targets]
    lines += [f".PHONY: {MAKE_TARGET}", f"{MAKE_TARGET}: $(CODECOREMORPH_CHARACTERIZATION)"]
    lines.append(f"\t-@mkdir -p {GTEST_OUTPUT_DIR}")
    # Each program says it runs (whatever `.SILENT:` says); a failure doesn't stop make.
    lines += [
        f"\t-@echo ./{name}; ./{name} "
        f"--gtest_output=xml:{GTEST_OUTPUT_DIR}/{name.replace('/', '_')}.xml"
        for name in names
    ]
    lines.append(END)
    return "\n".join(lines) + "\n"


def make_block_programs(text: str) -> list[str]:
    """The characterization programs of the marked block in a Makefile's ``text``."""
    start = text.find(BEGIN)
    if start < 0:
        return []
    listed = _LISTED.search(text, start)
    return listed.group(1).split() if listed is not None else []


def with_make_block(text: str, block: str | None) -> str:
    """``text`` (a top-level Makefile, ``Makefile.am`` or ``Makefile.in``) with ``block`` at its
    end in place of the marked block, in the file's line endings; without one when ``block``
    is None."""
    base = without_block(text)
    if block is None:
        return base
    newline = majority_newline(text) if "\n" in text else "\n"
    if base and not base.endswith("\n"):
        base += newline
    return base + (newline if base else "") + block.replace("\n", newline)
