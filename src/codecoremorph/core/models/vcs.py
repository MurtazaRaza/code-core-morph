"""What changed in a run worktree (FR-3.2): the diff summary stored per attempt."""

from __future__ import annotations

from enum import StrEnum

from pydantic import Field

from codecoremorph.core.models.base import CoreModel


class FileChangeKind(StrEnum):
    ADDED = "added"
    MODIFIED = "modified"
    DELETED = "deleted"
    TYPE_CHANGED = "type_changed"


class ChangedFile(CoreModel):
    path: str
    change: FileChangeKind
    added_lines: int | None = Field(default=None, ge=0, description="None for binary files")
    removed_lines: int | None = Field(default=None, ge=0, description="None for binary files")


class DiffResult(CoreModel):
    """A git-compatible unified diff against ``base``, generated by CodeCoreMorph."""

    base: str = Field(description="Commit the diff is taken against")
    patch: str = Field(description="Unified diff, decoded as UTF-8 with replacement characters")
    files: list[ChangedFile] = Field(default_factory=list[ChangedFile])

    @property
    def changed_lines(self) -> int:
        """Added plus removed lines over text files; what I-8 (diff size) limits."""
        return sum((f.added_lines or 0) + (f.removed_lines or 0) for f in self.files)

    @property
    def paths(self) -> list[str]:
        return [f.path for f in self.files]


class DirtyState(CoreModel):
    """Uncommitted changes in the user's working tree. They are never read or modified, and
    a run doesn't include them (FR-6.1)."""

    modified: list[str] = Field(default_factory=list[str])
    untracked: list[str] = Field(default_factory=list[str])

    @property
    def is_dirty(self) -> bool:
        return bool(self.modified or self.untracked)
