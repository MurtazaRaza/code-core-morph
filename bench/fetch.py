"""Fetch the pinned benchmark project (SPEC §12, D-10).

Usage: uv run python bench/fetch.py [--pin FILE] [DEST]

Clones the pin's repository (default bench/pin.json, M1's leveldb; bench/port-pin.json is M8's
snappy, bench/c-port-pin.json M9's bzip2, bench/rust-port-pin.json M10's shlex) at its pinned
commit, with submodules, into DEST (default: <CODECOREMORPH_HOME>/bench/<project>), then checks
that every commit matches the pin. Git verifies content by commit hash, so the pin is the
checksum. An existing clone at the right commits is left alone.

A pin with ``"lockfile": "generate"`` is a Rust crate without dependencies that doesn't commit
its Cargo.lock (a library often doesn't): the Rust adapter builds ``--locked``, so a commit on
top of the pinned one adds the lockfile, the package alone, with nothing to resolve.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tomllib
from pathlib import Path

from codecoremorph.core.paths import codecoremorph_home

PIN = Path(__file__).resolve().with_name("pin.json")
LOCK_MESSAGE = "bench: Cargo.lock for --locked builds (the crate has no dependencies)"
_DEPENDENCY_TABLES = ("dependencies", "dev-dependencies", "build-dependencies")


def git(*args: str, cwd: Path | None = None) -> str:
    result = subprocess.run(
        ["git", "-c", "core.autocrlf=false", *args],
        cwd=cwd,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        raise SystemExit(f"git {' '.join(args)} failed:\n{result.stderr}")
    return result.stdout.strip()


def verify(dest: Path, pin: dict[str, object]) -> list[str]:
    problems: list[str] = []
    head = git("rev-parse", "HEAD", cwd=dest)
    if pin.get("lockfile") == "generate" and git("log", "-1", "--format=%s", cwd=dest) == (
        LOCK_MESSAGE
    ):
        changed = git("diff", "--name-only", "HEAD^", "HEAD", cwd=dest).split()
        if changed != ["Cargo.lock"]:
            problems.append(f"the lockfile commit changes {changed}, not Cargo.lock alone")
        head = git("rev-parse", "HEAD^", cwd=dest)
    if head != pin["commit"]:
        problems.append(f"HEAD is {head}, expected {pin['commit']}")
    submodules = pin.get("submodules") or {}
    if not isinstance(submodules, dict):
        raise SystemExit("the pin's submodules must be an object")
    for path, commit in submodules.items():
        actual = git("rev-parse", "HEAD", cwd=dest / str(path))
        if actual != commit:
            problems.append(f"{path} is at {actual}, expected {commit}")
    return problems


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Fetch the pinned benchmark project.")
    parser.add_argument("--pin", type=Path, default=PIN, help="the benchmark's pin")
    parser.add_argument("dest", type=Path, nargs="?", help="where to clone it")
    args = parser.parse_args(argv)
    pin = json.loads(args.pin.read_text(encoding="utf-8"))
    dest: Path = args.dest or codecoremorph_home() / "bench" / str(pin["project"])
    if (dest / ".git").exists():
        problems = verify(dest, pin)
        if not problems:
            if pin.get("lockfile") == "generate":
                add_lockfile(dest)
            print(f"{dest} is already at {pin['project']} {pin['tag']} ({pin['commit'][:12]})")
            return 0
        print("existing clone doesn't match the pin:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1
    dest.parent.mkdir(parents=True, exist_ok=True)
    print(f"cloning {pin['url']} {pin['tag']} into {dest}")
    git(
        "clone",
        "--quiet",
        "--branch",
        str(pin["tag"]),
        "--depth",
        "1",
        "--recurse-submodules",
        "--shallow-submodules",
        str(pin["url"]),
        str(dest),
    )
    problems = verify(dest, pin)
    if problems:
        print("the clone doesn't match the pin:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1
    if pin.get("lockfile") == "generate":
        add_lockfile(dest)
    print(f"ok: {pin['project']} {pin['tag']} at {pin['commit']}")
    return 0


def lock_text(manifest: str) -> str:
    """The lockfile of a package without dependencies: the package alone (lockfile version 3,
    which every cargo since 1.53 reads)."""
    data = tomllib.loads(manifest)
    tables: list[object] = [data.get(t) for t in _DEPENDENCY_TABLES]
    for spec in (data.get("target") or {}).values():
        if isinstance(spec, dict):
            tables += [spec.get(t) for t in _DEPENDENCY_TABLES]
    if any(tables) or "workspace" in data:
        raise SystemExit(
            "the pin asks for a generated Cargo.lock, but the crate has dependencies or is a "
            "workspace, whose lockfile only cargo resolves: pin a commit that has one"
        )
    package = data["package"]
    return (
        "# This file is automatically @generated by Cargo.\n"
        "# It is not intended for manual editing.\n"
        "version = 3\n"
        "\n"
        "[[package]]\n"
        f'name = "{package["name"]}"\n'
        f'version = "{package["version"]}"\n'
    )


def add_lockfile(dest: Path) -> None:
    """Commit the generated lockfile on top of the pinned commit, unless the clone has one."""
    if (dest / "Cargo.lock").is_file():
        return
    text = lock_text((dest / "Cargo.toml").read_text(encoding="utf-8"))
    (dest / "Cargo.lock").write_text(text, encoding="utf-8", newline="\n")
    git("add", "--force", "Cargo.lock", cwd=dest)  # crates often ignore it
    git(
        "-c", "user.name=CodeCoreMorph bench", "-c", "user.email=bench@codecoremorph.invalid",
        "commit", "--quiet", "-m", LOCK_MESSAGE, cwd=dest,
    )  # fmt: skip
    print(f"committed a generated Cargo.lock on top of {dest.name}'s pinned commit")


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
