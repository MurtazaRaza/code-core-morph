"""A port's crate with a Cargo feature for a configuration of the source (D-89): the tests
run with the default features and again with each feature alone, its IDs ending in
``[<feature>]``, so a configuration's tests are checked like the others (http-parser's
strict checks ran in nothing before). A crate being ported to C gets them too, since its C
keeps what each feature turns on; a Rust project with no port doesn't. Marked ``docker``."""

from __future__ import annotations

from collections.abc import Iterator
from dataclasses import replace
from pathlib import Path

import pytest

from codecoremorph.adapters.base import AdapterContext
from codecoremorph.adapters.rust import RustAdapter
from codecoremorph.core.errors import SandboxError
from codecoremorph.core.ids import new_run_id
from codecoremorph.core.models import LanguageConfig, TestStatus

pytestmark = pytest.mark.docker

CRATE = {
    "rust/Cargo.toml": '[workspace]\nmembers = ["mode_rs"]\nresolver = "2"\n',
    "rust/Cargo.lock": (
        "# This file is automatically @generated by Cargo.\n"
        "# It is not intended for manual editing.\nversion = 4\n\n"
        '[[package]]\nname = "mode_rs"\nversion = "0.1.0"\n'
    ),
    "rust/mode_rs/Cargo.toml": (
        '[package]\nname = "mode_rs"\nversion = "0.1.0"\nedition = "2021"\n\n'
        "[features]\nstrict = []\n"
    ),
    "rust/mode_rs/src/lib.rs": (
        "//! A parser's mode.\n\n/// Whether the strict checks are on.\n"
        'pub const STRICT: bool = cfg!(feature = "strict");\n'
    ),
    "rust/mode_rs/tests/mode.rs": (
        "#[test]\nfn the_mode_is_the_features() {\n"
        '    assert_eq!(mode_rs::STRICT, cfg!(feature = "strict"));\n}\n\n'
        '#[cfg(feature = "strict")]\n#[test]\nfn strict_checks_hold() {\n'
        "    assert!(mode_rs::STRICT);\n}\n"
    ),
}


@pytest.fixture
def ctx(tmp_path: Path) -> Iterator[AdapterContext]:
    from codecoremorph.sandbox.docker.executor import DockerExecutor, DockerSettings
    from codecoremorph.sandbox.provisioning import resolve_image

    work = tmp_path / "work"
    for rel, text in CRATE.items():
        (work / rel).parent.mkdir(parents=True, exist_ok=True)
        (work / rel).write_bytes(text.encode("utf-8"))
    for name in ("build", "cache", "logs"):
        (tmp_path / name).mkdir()
    lang = LanguageConfig(
        language="rust",
        standard="rust2021",
        target_standard="rust2021",
        port_source="c",
        build_timeout_s=900,
        test_timeout_s=600,
    )
    try:
        image = resolve_image(RustAdapter().toolchain_requirements(lang), None)
    except SandboxError as exc:
        pytest.skip(f"no Rust toolchain image: {exc}")
    executor = DockerExecutor(
        DockerSettings(
            image=image,
            run_id=new_run_id(),
            worktree=work,
            build_dir=tmp_path / "build",
            cache_dir=tmp_path / "cache",
            log_dir=tmp_path / "exec",
            toolchain_env="/opt/codecoremorph/toolchains/rust.env",
        )
    )
    executor.start()
    try:
        yield AdapterContext(
            worktree=work,
            build_dir=tmp_path / "build",
            cache_dir=tmp_path / "cache",
            log_dir=tmp_path / "logs",
            executor=executor,
            lang=lang,
        )
    finally:
        executor.stop()


def test_a_ports_features_are_tested_alone(ctx: AdapterContext) -> None:
    rust = RustAdapter()
    statuses = {t.test_id: t.status for t in rust.run_tests(ctx).cases}
    test = "nextest:mode_rs::mode::"
    assert statuses == {
        f"{test}the_mode_is_the_features": TestStatus.PASSED,
        f"{test}the_mode_is_the_features[strict]": TestStatus.PASSED,
        f"{test}strict_checks_hold[strict]": TestStatus.PASSED,
    }
    # A crate being ported to C: its C keeps what each feature turns on, so the same runs.
    to_c = ctx.lang.model_copy(update={"port_source": None, "port_target": "c"})
    assert {t.test_id for t in rust.run_tests(replace(ctx, lang=to_c)).cases} == set(statuses)
    alone = ctx.lang.model_copy(update={"port_source": None})  # no port: the crate's own tests
    plain = {t.test_id for t in rust.run_tests(replace(ctx, lang=alone)).cases}
    assert plain == {f"{test}the_mode_is_the_features"}
