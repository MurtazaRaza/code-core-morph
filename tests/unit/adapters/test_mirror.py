"""The mirror a build tool writes into instead of the run worktree (D-68)."""

from __future__ import annotations

import os
import stat
import sys
from pathlib import Path

import pytest

from codecoremorph.adapters.mirror import MANIFEST_NAME, Mirror


def _worktree(tmp_path: Path) -> Path:
    work = tmp_path / "work"
    (work / "src").mkdir(parents=True)
    (work / "Makefile").write_bytes(b"all: placeholder\n")
    (work / "Makefile.in").write_bytes(b"all: real\n")
    (work / "src" / "a.c").write_bytes(b"int a;\n")
    (work / ".git").write_bytes(b"gitdir: elsewhere\n")  # a worktree's .git file
    (work / ".codecoremorph").mkdir()
    (work / ".codecoremorph" / "lock").write_bytes(b"{}")
    return work


def test_the_first_sync_copies_the_project_but_not_git_or_the_store(tmp_path: Path) -> None:
    mirror = Mirror(_worktree(tmp_path), tmp_path / "mirror")
    assert mirror.sync() == ["Makefile", "Makefile.in", "src/a.c"]
    assert (tmp_path / "mirror" / "src" / "a.c").read_bytes() == b"int a;\n"
    assert not (tmp_path / "mirror" / ".git").exists()
    assert not (tmp_path / "mirror" / ".codecoremorph").exists()
    assert mirror.sync() == []  # nothing changed


def test_what_the_build_writes_stays_until_the_worktree_changes_it(tmp_path: Path) -> None:
    """zlib commits a placeholder Makefile that ./configure replaces: syncing must not put
    the placeholder back, but a new worktree version wins."""
    work = _worktree(tmp_path)
    mirror = Mirror(work, tmp_path / "mirror")
    mirror.sync()
    (tmp_path / "mirror" / "Makefile").write_bytes(b"all: generated by configure\n")
    (tmp_path / "mirror" / "src" / "a.o").write_bytes(b"\x7fELF")
    assert mirror.sync() == []
    assert (tmp_path / "mirror" / "Makefile").read_bytes() == b"all: generated by configure\n"
    assert (tmp_path / "mirror" / "src" / "a.o").is_file()  # build output stays

    (work / "Makefile").write_bytes(b"all: edited\n")
    assert mirror.sync() == ["Makefile"]
    assert (tmp_path / "mirror" / "Makefile").read_bytes() == b"all: edited\n"


def test_a_file_the_worktree_deletes_goes_from_the_mirror(tmp_path: Path) -> None:
    work = _worktree(tmp_path)
    mirror = Mirror(work, tmp_path / "mirror")
    mirror.sync()
    (work / "src" / "a.c").unlink()
    (work / "src" / "b.c").write_bytes(b"int b;\n")
    assert mirror.sync() == ["src/a.c", "src/b.c"]
    assert not (tmp_path / "mirror" / "src" / "a.c").exists()
    assert (tmp_path / "mirror" / "src" / "b.c").is_file()


def test_an_unchanged_file_keeps_its_time_and_a_changed_one_is_newer(tmp_path: Path) -> None:
    """make rebuilds what depends on a changed file and nothing else."""
    work = _worktree(tmp_path)
    mirror = Mirror(work, tmp_path / "mirror")
    mirror.sync()
    copy = tmp_path / "mirror" / "src" / "a.c"
    other = tmp_path / "mirror" / "Makefile.in"
    os.utime(copy, (1_000_000, 1_000_000))
    os.utime(other, (1_000_000, 1_000_000))
    (work / "src" / "a.c").write_bytes(b"int a = 1;\n")
    mirror.sync()
    assert copy.stat().st_mtime > 1_000_000
    assert other.stat().st_mtime == 1_000_000


def test_skipped_directories_and_the_manifest(tmp_path: Path) -> None:
    work = _worktree(tmp_path)
    (work / "build").mkdir()
    (work / "build" / "x.o").write_bytes(b"")
    mirror = Mirror(work, tmp_path / "mirror", skip_dir=lambda parent, name: name == "build")
    assert "build/x.o" not in mirror.sync()
    assert (tmp_path / "mirror" / MANIFEST_NAME).is_file()
    assert MANIFEST_NAME not in mirror.worktree_files()
    mirror.wipe()
    assert not (tmp_path / "mirror").exists()


@pytest.mark.skipif(sys.platform == "win32", reason="POSIX permission bits")
def test_an_executable_script_stays_executable(tmp_path: Path) -> None:
    work = _worktree(tmp_path)
    script = work / "configure"
    script.write_bytes(b"#!/bin/sh\n")
    script.chmod(0o755)
    Mirror(work, tmp_path / "mirror").sync()
    assert (tmp_path / "mirror" / "configure").stat().st_mode & stat.S_IXUSR
